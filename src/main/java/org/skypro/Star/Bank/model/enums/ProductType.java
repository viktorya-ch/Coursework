package org.skypro.Star.Bank.model.enums;

/**
 * Типы банковских продуктов
 */

public enum ProductType {
    /**
     * Дебетовые продукты (карты, счета)
     */
    DEBIT,
    /**
     * Кредитные продукты (кредиты, займы)
     */
    CREDIT,
    /**
     * Сберегательные продукты (вклады, накопительные счета)
     */
    SAVING,
    /**
     * Инвестиционные продукты (ИИС, брокерские счета)
     */
    INVEST
}
